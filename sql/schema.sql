/*Table: COUPON */
CREATE TABLE COUPON (
   ID_COUPON INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   CODE VARCHAR(50) NOT NULL UNIQUE,
   TYPE VARCHAR(20) NOT NULL, -- 'percentage' hoặc 'fixed'
   DISCOUNT NUMERIC(15,2) NOT NULL,
   MIN_ORDER_VALUE NUMERIC(15,2) NOT NULL DEFAULT 0,
   MAX_USER INT NOT NULL DEFAULT 1,
   USED_COUNT INT NOT NULL DEFAULT 0,
   EXPIRED_AT TIMESTAMP NOT NULL,
   CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   UPDATED_AT TIMESTAMP,
   DELETED_AT TIMESTAMP
);

/*Table: OAUTH*/
CREATE TABLE OAUTH_ACCOUNT (
   ID            BIGSERIAL    PRIMARY KEY,
   UUID          VARCHAR(50)  NOT NULL,
   PROVIDER      VARCHAR(50)  NOT NULL,   -- 'google' | 'facebook' | 'github'
   PROVIDER_ID   VARCHAR(255) NOT NULL,   -- ID user từ phía provider
   ACCESS_TOKEN  TEXT,
   REFRESH_TOKEN TEXT,
   EXPIRED_AT    TIMESTAMP,
   CREATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
   UPDATED_AT    TIMESTAMP,
   CONSTRAINT FK_OAUTH_USER
      FOREIGN KEY (UUID) REFERENCES "USER" (UUID)
         ON DELETE CASCADE ON UPDATE RESTRICT,
   -- Đảm bảo mỗi tài khoản provider chỉ map 1 user
   CONSTRAINT UQ_OAUTH_PROVIDER_ID UNIQUE (PROVIDER, PROVIDER_ID)
);

