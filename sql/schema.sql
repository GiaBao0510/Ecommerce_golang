-- [NEW-D4] Bảng CART header: CART_ITEM cần bảng cha để quản lý trạng thái
CREATE TABLE CART (
   ID_CART    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   UUID       VARCHAR(50) NOT NULL UNIQUE,   -- 1 user = 1 active cart
   CREATED_AT TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
   UPDATED_AT TIMESTAMP,
   CONSTRAINT FK_CART_USER
      FOREIGN KEY (UUID) REFERENCES "USER" (UUID)
         ON DELETE CASCADE ON UPDATE RESTRICT
);
 
-- [NEW-D4] Thêm FK tới CART (bảng cha); thêm UNIQUE tránh trùng sản phẩm trong giỏ
CREATE TABLE CART_ITEM (
   ID_CART_ITEM INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   ID_CART      INT         NOT NULL,
   ID_PRODUCT   VARCHAR(50) NOT NULL,
   QUANTITY     INT         NOT NULL DEFAULT 1 CHECK (QUANTITY > 0),
   CREATED_AT   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
   UPDATED_AT   TIMESTAMP,
   DELETED_AT   TIMESTAMP,
   CONSTRAINT FK_CART_ITEM_CART
      FOREIGN KEY (ID_CART) REFERENCES CART (ID_CART)
         ON DELETE CASCADE ON UPDATE RESTRICT,
   CONSTRAINT FK_CART_ITEM_PRODUCT
      FOREIGN KEY (ID_PRODUCT) REFERENCES PRODUCT (ID_PRODUCT)
         ON DELETE RESTRICT ON UPDATE RESTRICT,
   CONSTRAINT UQ_CART_ITEM UNIQUE (ID_CART, ID_PRODUCT)
);

