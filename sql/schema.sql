/* Table: BRAND                                                 */
CREATE TABLE BRAND (
   ID_BRAND INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   NAME VARCHAR(255) NOT NULL,
   CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
   UPDATED_AT TIMESTAMP,
   DELETED_AT TIMESTAMP
);

/* Table: CATEGORIES                                            */
